//! Component cache. Every reusable UI spec is stored as cache/components/<name>.json and listed,
//! with its path, use count and engagement, in cache/registry.md (the memory file Claude reads
//! before building something new, so it reuses instead of re-spending tokens).

use crate::{engagement, paths, protocol::Opts};
use serde_json::{json, Value};
use std::fs;
use std::path::PathBuf;

fn file_for(name: &str) -> PathBuf {
    let safe: String = name.chars().map(|c| if c.is_ascii_alphanumeric() || c == '-' || c == '_' { c } else { '_' }).collect();
    paths::components_dir().join(format!("{safe}.json"))
}

pub fn save(name: &str, desc: &str, params: &[String], opts: &Opts, components: &[Value], data: &Value, sources: &Value) -> Result<PathBuf, String> {
    let p = file_for(name);
    let doc = json!({
        "name": name, "desc": desc, "params": params,
        "opts": opts, "components": components, "data": data, "sources": sources,
    });
    fs::create_dir_all(paths::components_dir()).map_err(|e| e.to_string())?;
    fs::write(&p, serde_json::to_string_pretty(&doc).unwrap()).map_err(|e| e.to_string())?;
    write_registry();
    Ok(p)
}

pub fn load(name: &str) -> Option<Value> {
    // PowerShell writes a BOM; a cached spec edited by hand or by an agent must still load
    serde_json::from_str(fs::read_to_string(file_for(name)).ok()?.trim_start_matches('\u{feff}')).ok()
}

pub fn all() -> Vec<Value> {
    let Ok(rd) = fs::read_dir(paths::components_dir()) else { return vec![] };
    let mut v: Vec<Value> = rd
        .filter_map(|e| e.ok())
        .filter_map(|e| fs::read_to_string(e.path()).ok())
        .filter_map(|s| serde_json::from_str(s.trim_start_matches('\u{feff}')).ok())
        .collect();
    v.sort_by(|a, b| a["name"].as_str().cmp(&b["name"].as_str()));
    v
}

fn usage() -> Value {
    fs::read_to_string(paths::usage_file()).ok().and_then(|s| serde_json::from_str(&s).ok()).unwrap_or(json!({}))
}

pub fn bump_use(name: &str) {
    let mut u = usage();
    let n = u[name]["uses"].as_u64().unwrap_or(0) + 1;
    u[name] = json!({"uses": n, "last": crate::util::now_ms() as u64});
    let _ = fs::write(paths::usage_file(), u.to_string());
}

/// Rewrite cache/registry.md from what is on disk.
pub fn write_registry() {
    let u = usage();
    let mut md = String::from(
        "# Morceau component registry\n\n\
         Auto-generated by `morc save` / `morc registry`. Read this BEFORE building a new surface: reuse with\n\
         `morc use <name> --data '{...}'` (cheapest in tokens). Specs live in `cache/components/<name>.json`.\n\n\
         | name | what it is | params (data paths to override) | spec file | uses | interest |\n|---|---|---|---|---|---|\n",
    );
    for c in all() {
        let name = c["name"].as_str().unwrap_or("?");
        let params = c["params"].as_array().map(|a| a.iter().filter_map(|x| x.as_str()).collect::<Vec<_>>().join(", ")).unwrap_or_default();
        let topic = c["opts"]["topic"].as_str().unwrap_or(name);
        md.push_str(&format!(
            "| `{}` | {} | {} | `cache/components/{}` | {} | {:.2} |\n",
            name,
            c["desc"].as_str().unwrap_or(""),
            params,
            file_for(name).file_name().unwrap().to_string_lossy(),
            u[name]["uses"].as_u64().unwrap_or(0),
            engagement::score(topic),
        ));
    }
    let _ = fs::write(paths::cache_dir().join("registry.md"), md);
}
