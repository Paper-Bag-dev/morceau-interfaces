# morc ui: the UI component tree. Usage: morc ui build | list | map | show NAME | new NAME [--deps a,b] [--types t1,t2]
"""Every UI component is its own folder, ui/components/<name>/, holding its code (<name>.js), its styles (<name>.css) and a metadata.json
(name, description, types it registers, deps, tokens it reads). `morc ui build` reads those folders, orders them by dependency (a component loads after the
things it depends on) and writes the two files everyone starts from:
  ui/components.json   the manifest the page loads (order, paths, types, deps)
  ui/COMPONENTS.md     the index: where everything is. Read it first, then fetch only the folder you need.
Nothing is merged into a big file: change a component by editing its folder, then run `morc ui build`."""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _home import APP, BIN  # noqa: E402

UI = os.path.join(APP, "ui")
COMP = os.path.join(UI, "components")


def host_map():
    """The component map held in the host's memory (`morc uimap`): paths, deps, types, tokens. None if the host is not running."""
    import subprocess
    try:
        r = subprocess.run([BIN, "uimap"], capture_output=True, text=True, timeout=8)
        d = json.loads(r.stdout)
        return d if d.get("ok") else None
    except (OSError, ValueError, subprocess.SubprocessError):
        return None


def read_all():
    out = {}
    for name in sorted(os.listdir(COMP)):
        p = os.path.join(COMP, name, "metadata.json")
        if os.path.isfile(p):
            m = json.load(open(p, encoding="utf-8-sig"))
            m["name"] = m.get("name") or name
            m["path"] = f"components/{name}"
            out[name] = m
    return out


def order(metas):
    seen, stack, out = set(), set(), []

    def visit(n):
        if n in seen:
            return
        if n in stack:
            raise SystemExit("dependency cycle at " + n)
        if n not in metas:
            raise SystemExit("unknown dependency: " + n)
        stack.add(n)
        for d in metas[n].get("deps", []):
            visit(d)
        stack.discard(n)
        seen.add(n)
        out.append(n)

    for n in sorted(metas):
        visit(n)
    return out


def check(metas):
    problems = []
    for n, m in metas.items():
        for key in ("js", "css"):
            if m.get(key) and not os.path.isfile(os.path.join(COMP, n, m[key])):
                problems.append(f"{n}: {key} file {m[key]} is missing")
    return problems


def build():
    metas = read_all()
    problems = check(metas)
    if problems:
        print("\n".join(problems))
        return 1
    ordered = order(metas)
    manifest = {"order": ordered, "components": {n: {k: metas[n].get(k) for k in ("path", "js", "css", "types", "deps", "tokens", "description")} for n in ordered}}
    json.dump(manifest, open(os.path.join(UI, "components.json"), "w", encoding="utf-8"), indent=1)
    lines = ["# UI components: the index", "",
             "Generated by `morc ui build` from `ui/components/<name>/metadata.json`. Do not edit by hand: edit a component's folder, then run the command.",
             "Each component is one folder with its code, its styles and its metadata. A component loads after the things it depends on.", "",
             "| component | what | registers | depends on | files | tokens |", "|---|---|---|---|---|---|"]
    for n in ordered:
        m = metas[n]
        files = ", ".join(f"`{m[k]}`" for k in ("js", "css") if m.get(k)) + ", `metadata.json`"
        lines.append(f"| `{n}` | {m.get('description', '')} | {', '.join(m.get('types', [])) or 'style only'} | {', '.join(m.get('deps', [])) or '-'} | {files} | {', '.join(m.get('tokens', [])) or '-'} |")
    lines += ["", "Paths: `ui/components/<name>/`. Page entry: `ui/core/main.js` loads `ui/components.json` in this order. Tokens live in `ui/tokens/<component>.json`,",
              "limits in `ui/limits.json`, colors in `ui/themes.json` (each hot-reloaded). To add a component: `morc ui new <name> --deps plate --types mytype`.",
              "The host keeps this map in memory (hot-reloaded with the other UI files); pull it any time with `morc uimap` or `morc ui map` (absolute paths), `morc ui list` (summary).", ""]
    open(os.path.join(UI, "COMPONENTS.md"), "w", encoding="utf-8").write("\n".join(lines))
    print(f"built {len(ordered)} components: " + ", ".join(ordered))
    return 0


def new(name, deps, types):
    d = os.path.join(COMP, name)
    os.makedirs(d, exist_ok=True)
    js = os.path.join(d, name + ".js")
    if not os.path.exists(js):
        open(js, "w", encoding="utf-8").write("import { register } from '../../core/registry.js';\n\n" + "\n".join(f"register('{t}', (c, ctx) => {{\n  const el = document.createElement('div');\n  el.dataset.hit = '';\n  return el;\n}});" for t in (types or [name])) + "\n")
    css = os.path.join(d, name + ".css")
    if not os.path.exists(css):
        open(css, "w", encoding="utf-8").write(f"/* {name}: styles for this component only. Sizes come from tokens (ui/tokens/{name}.json) as var(--{name}-..., fallback). */\n")
    meta = {"name": name, "description": "", "types": types or [name], "js": name + ".js", "css": name + ".css", "deps": deps, "tokens": []}
    json.dump(meta, open(os.path.join(d, "metadata.json"), "w", encoding="utf-8"), indent=2)
    print("created " + d)
    return build()


def main(argv):
    cmd = argv[0] if argv else "list"
    if cmd == "build":
        return build()
    if cmd == "map":  # the component map from the running host's memory (hot-reloaded), with absolute paths
        hm = host_map()
        if not hm:
            print("the host is not running; use `morc ui list` (reads the folders)")
            return 1
        print(json.dumps(hm, indent=1))
        return 0
    if cmd == "list":
        hm = host_map()   # pulled from the host's memory when it is up, else read from the folders
        if hm and hm.get("map", {}).get("order"):
            for n in hm["map"]["order"]:
                m = hm["map"]["components"][n]
                print(f"{n:10} deps={','.join(m.get('deps') or []) or '-':8} types={','.join(m.get('types') or []) or 'style'}  {m['path']}   (from the host)")
            return 0
        metas = read_all()
        for n in order(metas):
            m = metas[n]
            print(f"{n:10} deps={','.join(m.get('deps', [])) or '-':8} types={','.join(m.get('types', [])) or 'style'}  {m['path']}")
        return 0
    if cmd == "show" and len(argv) > 1:
        m = read_all().get(argv[1])
        if not m:
            print("no component " + argv[1])
            return 1
        print(json.dumps(m, indent=1))
        return 0
    if cmd == "new" and len(argv) > 1:
        def flag(k):
            return argv[argv.index(k) + 1].split(",") if k in argv else []
        return new(argv[1], flag("--deps"), flag("--types"))
    print(__doc__)
    return 2


sys.exit(main(sys.argv[1:]))
